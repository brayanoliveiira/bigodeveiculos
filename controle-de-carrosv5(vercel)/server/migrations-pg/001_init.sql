CREATE TABLE audit (
  id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts       TEXT NOT NULL,
  userId   BIGINT,
  entity   TEXT NOT NULL,
  entityId BIGINT,
  label    TEXT,
  action   TEXT NOT NULL,
  changes  TEXT NOT NULL DEFAULT '[]'
);
CREATE INDEX idx_audit_ts ON audit (ts DESC);

CREATE FUNCTION audit_readonly() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'O histórico é somente de inclusão'; END; $$;
CREATE TRIGGER audit_no_update BEFORE UPDATE ON audit FOR EACH ROW EXECUTE FUNCTION audit_readonly();
CREATE TRIGGER audit_no_delete BEFORE DELETE ON audit FOR EACH ROW EXECUTE FUNCTION audit_readonly();

