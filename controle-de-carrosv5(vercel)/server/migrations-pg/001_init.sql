CREATE TABLE cars (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name      TEXT NOT NULL,
  placa     TEXT,
  ano       INTEGER,
  dcompra   TEXT,
  entT      DOUBLE PRECISION,
  ovrA      DOUBLE PRECISION,
  ovrB      DOUBLE PRECISION,
  origemId  BIGINT REFERENCES cars (id),
  anun      DOUBLE PRECISION,
  loc       TEXT,
  locdet    TEXT,
  locdesde  TEXT,
  locprev   TEXT,
  status    TEXT NOT NULL DEFAULT 'Em estoque',
  dvenda    TEXT,
  vvenda    DOUBLE PRECISION,
  quemrec   TEXT CHECK (quemrec IS NULL OR quemrec IN ('A', 'B')),
  comprador TEXT,
  divis     TEXT,
  pcust     DOUBLE PRECISION CHECK (pcust IS NULL OR (pcust >= 0 AND pcust <= 1)),
  cor       TEXT,
  fipe      DOUBLE PRECISION,
  fipeRef   TEXT,
  dono      TEXT,
  repasse   DOUBLE PRECISION,
  example   INTEGER NOT NULL DEFAULT 0,
  deleted   INTEGER NOT NULL DEFAULT 0,
  createdBy BIGINT,
  createdAt TEXT,
  updatedBy BIGINT,
  updatedAt TEXT
);

CREATE TABLE expenses (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  carId     BIGINT NOT NULL REFERENCES cars (id),
  date      TEXT NOT NULL,
  cat       TEXT NOT NULL,
  "desc"    TEXT,
  valor     DOUBLE PRECISION NOT NULL,
  quem      TEXT NOT NULL CHECK (quem IN ('A', 'B')),
  obs       TEXT,
  example   INTEGER NOT NULL DEFAULT 0,
  deleted   INTEGER NOT NULL DEFAULT 0,
  createdBy BIGINT,
  createdAt TEXT,
  updatedBy BIGINT,
  updatedAt TEXT
);
CREATE INDEX idx_expenses_car ON expenses (carId);

CREATE TABLE planned (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  carId     BIGINT NOT NULL REFERENCES cars (id),
  cat       TEXT NOT NULL,
  "desc"    TEXT,
  valor     DOUBLE PRECISION NOT NULL,
  quem      TEXT CHECK (quem IS NULL OR quem IN ('A', 'B')),
  prazo     TEXT,
  status    TEXT NOT NULL DEFAULT 'Pendente',
  example   INTEGER NOT NULL DEFAULT 0,
  deleted   INTEGER NOT NULL DEFAULT 0,
  createdBy BIGINT,
  createdAt TEXT,
  updatedBy BIGINT,
  updatedAt TEXT
);
CREATE INDEX idx_planned_car ON planned (carId);

CREATE TABLE receipts (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  carId     BIGINT NOT NULL REFERENCES cars (id),
  label     TEXT,
  due       TEXT NOT NULL,
  valor     DOUBLE PRECISION NOT NULL,
  status    TEXT NOT NULL DEFAULT 'Pendente',
  paidAt    TEXT,
  quem      TEXT CHECK (quem IS NULL OR quem IN ('A', 'B')),
  obs       TEXT,
  example   INTEGER NOT NULL DEFAULT 0,
  deleted   INTEGER NOT NULL DEFAULT 0,
  createdBy BIGINT,
  createdAt TEXT,
  updatedBy BIGINT,
  updatedAt TEXT
);
CREATE INDEX idx_receipts_car ON receipts (carId);

CREATE TABLE repasses (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  carId     BIGINT NOT NULL REFERENCES cars (id),
  date      TEXT NOT NULL,
  valor     DOUBLE PRECISION NOT NULL,
  quem      TEXT CHECK (quem IS NULL OR quem IN ('A', 'B')),
  obs       TEXT,
  example   INTEGER NOT NULL DEFAULT 0,
  deleted   INTEGER NOT NULL DEFAULT 0,
  createdBy BIGINT,
  createdAt TEXT,
  updatedBy BIGINT,
  updatedAt TEXT
);
CREATE INDEX idx_repasses_car ON repasses (carId);

CREATE TABLE payments (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receiptId BIGINT NOT NULL REFERENCES receipts (id),
  date      TEXT NOT NULL,
  valor     DOUBLE PRECISION NOT NULL,
  quem      TEXT CHECK (quem IS NULL OR quem IN ('A', 'B')),
  obs       TEXT,
  example   INTEGER NOT NULL DEFAULT 0,
  deleted   INTEGER NOT NULL DEFAULT 0,
  createdBy BIGINT,
  createdAt TEXT,
  updatedBy BIGINT,
  updatedAt TEXT
);
CREATE INDEX idx_payments_receipt ON payments (receiptId);

