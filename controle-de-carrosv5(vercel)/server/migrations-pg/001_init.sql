-- Esquema do PostgreSQL (Supabase). Espelha server/migrations/*.sql do SQLite, já na forma final.
-- Regra: nomes de colunas SEM aspas (o Postgres guarda em minúsculas; o app devolve com a caixa do código).
-- Para mudar o banco, crie 002_*.sql... (nunca edite um arquivo já aplicado) e faça o mesmo em server/migrations/.
-- Datas são texto AAAA-MM-DD; carimbos são texto ISO 8601 UTC; dinheiro é DOUBLE PRECISION em reais.

CREATE TABLE users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      TEXT NOT NULL,
  name          TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role          TEXT NOT NULL CHECK (role IN ('admin', 'member', 'viewer')),
  active        INTEGER NOT NULL DEFAULT 1,
  created_at    TEXT NOT NULL,
  last_login    TEXT
);
CREATE UNIQUE INDEX users_username_ci ON users (lower(username));

CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES users (id),
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL
);
CREATE INDEX idx_sessions_user ON sessions (user_id);

CREATE TABLE settings (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL
